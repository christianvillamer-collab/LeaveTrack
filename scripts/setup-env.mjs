import { existsSync, writeFileSync } from "node:fs";

const target = ".env.local";

if (existsSync(target)) {
  process.stdout.write(".env.local already exists; leaving it untouched.\n");
  process.exit(0);
}

const content = `# Local development defaults — generated by \`npm run env:setup\`.
# This file is gitignored. Replace the DB URLs with Supabase pooled/direct
# connections when you are not using the local Docker Postgres.
NEXT_PUBLIC_APP_URL="http://localhost:3000"
LOG_LEVEL="info"

# Local Docker Postgres (npm run db:up), host port 55432.
DATABASE_URL="postgres://leavetrack:leavetrack@localhost:55432/leavetrack"
DIRECT_URL="postgres://leavetrack:leavetrack@localhost:55432/leavetrack"

# Day 1 providers — not used by the current code.
NEXT_PUBLIC_SUPABASE_URL=""
NEXT_PUBLIC_SUPABASE_ANON_KEY=""
SUPABASE_SERVICE_ROLE_KEY=""
CRON_SECRET=""
`;

writeFileSync(target, content, { mode: 0o600 });
process.stdout.write(
  "Created .env.local with local Postgres defaults. Next: npm run db:up && npm run db:migrate && npm run db:seed\n",
);
